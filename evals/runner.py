"""Step runner used by run_evals_core.py and run_evals_extra.py (repo root).

Each step is one harness command. Every harness saves each finished query immediately and skips saved
queries when re-run (--resume), so a step can be interrupted at any point and continued later. The runner:
  * runs the steps in order, echoing output to the terminal and to <results>/logs/<step>.log
  * exit 0 (all queries saved)      -> next step
  * exit 2 (some queries failed)    -> runs the step again (up to PASSES times), then moves on
  * exit 75 (quota/billing/outage)  -> stops the whole run; re-run the same script later to continue
  * always finishes by rebuilding report.md from whatever has been saved so far
"""
import datetime
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "evals"))
from run_status import EXIT_DONE, EXIT_PARTIAL, EXIT_STOPPED  # noqa: E402

RESULTS = ROOT / "evals" / "results" / "gemini_v2"
ARCHIVE = ROOT / "evals" / "results" / "archive"
PY = sys.executable
PASSES = 3        # attempts per step and session when some queries fail for a non-quota reason

ENV = {
    "EVAL_RESULTS_DIR": str(RESULTS),
    "LLM_PROVIDER": "gemini",
    "GEMINI_TEMPERATURE": os.getenv("GEMINI_TEMPERATURE", "0"),   # baselines use 0; the pipeline now does too
    "PYTHONUNBUFFERED": "1",
}


class Step:
    def __init__(self, name: str, args: list, llm: bool = True, needs: str | None = None,
                 output: str | None = None):
        # needs:  file in the results folder that must exist before the step can run
        # output: file the step writes in one go; once it exists the step is not run again
        self.name, self.args, self.llm, self.needs, self.output = name, args, llm, needs, output


def harness(*args) -> list:
    return [PY, *args]


def _log(step: str):
    d = RESULTS / "logs"
    d.mkdir(parents=True, exist_ok=True)
    return open(d / f"{step}.log", "a", encoding="utf-8")


def run_step(step: Step) -> int:
    env = {**os.environ, **ENV}
    with _log(step.name) as log:
        log.write(f"\n===== {datetime.datetime.now().isoformat(timespec='seconds')} {' '.join(step.args[1:])}\n")
        proc = subprocess.Popen(step.args, cwd=ROOT, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                text=True, bufsize=1)
        try:
            for line in proc.stdout:
                if "Loading weights" in line or "UserWarning" in line:
                    continue
                sys.stdout.write(line)
                log.write(line)
            return proc.wait()
        except KeyboardInterrupt:
            proc.wait()   # the child saves its progress and exits on the same Ctrl+C
            raise


def ensure_database() -> bool:
    check = [PY, "-c", "import sys; sys.path.insert(0, '.');"
             "from legal_workflow_generator.agent.nodes import _connect; _connect().close()"]
    if subprocess.run(check, cwd=ROOT, capture_output=True).returncode == 0:
        return True
    print("Postgres is not reachable; trying `docker start pgvector-db` ...")
    subprocess.run(["docker", "start", "pgvector-db"], capture_output=True)
    for _ in range(30):
        if subprocess.run(check, cwd=ROOT, capture_output=True).returncode == 0:
            return True
        time.sleep(1)
    print("ERROR: Postgres is still not reachable. Start it (docker compose up -d) and re-run.")
    return False


def copy_archived_baselines() -> None:
    """The paper's saved baselines (gemini-3.1-flash-lite, temperature 0, same queries and corpus) are reused.
    The archived file baseline_rag_hybrid.jsonl is the ABSTAINING run (its no-abstain twin was overwritten),
    so it is stored under its correct name; the no-abstain run is regenerated by a step."""
    RESULTS.mkdir(parents=True, exist_ok=True)
    for src, dst in (("baseline_llm_only.jsonl", "baseline_llm_only.jsonl"),
                     ("baseline_llm_pure.jsonl", "baseline_llm_pure.jsonl"),
                     ("baseline_rag_bm25.jsonl", "baseline_rag_bm25.jsonl"),
                     ("baseline_rag_hybrid.jsonl", "baseline_rag_hybrid_abstain.jsonl")):
        if not (RESULTS / dst).exists() and (ARCHIVE / src).exists():
            shutil.copy2(ARCHIVE / src, RESULTS / dst)
            print(f"reused archived baseline: {src} -> {dst}")


class Lock:
    def __init__(self, name: str):
        self.path = RESULTS / "logs" / f".{name}.lock"

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        if self.path.exists():
            try:
                pid = int(self.path.read_text().strip())
                os.kill(pid, 0)
                sys.exit(f"Another run (pid {pid}) is still going. Wait for it or stop it first.")
            except (ValueError, ProcessLookupError, PermissionError):
                pass   # stale lock from a crashed run
        self.path.write_text(str(os.getpid()))
        return self

    def __exit__(self, *exc):
        self.path.unlink(missing_ok=True)


def run_all(title: str, steps: list) -> int:
    print(f"\n{'#' * 70}\n# {title}\n# results: {RESULTS}\n{'#' * 70}")
    status = {}
    stopped = False
    with Lock(title.split()[0].lower()):
        if not ensure_database():
            return 1
        try:
            for step in steps:
                if stopped:
                    status[step.name] = "not started (stopped earlier)"
                    continue
                if step.output and (RESULTS / step.output).exists():
                    status[step.name] = "complete"
                    continue
                if step.needs and not (RESULTS / step.needs).exists():
                    status[step.name] = f"skipped (waits for {step.needs})"
                    continue
                print(f"\n{'=' * 70}\n>>> {step.name}\n{'=' * 70}", flush=True)
                code = EXIT_PARTIAL
                for attempt in range(1, PASSES + 1):
                    code = run_step(step)
                    if code != EXIT_PARTIAL:
                        break
                    print(f"[{step.name}] some queries failed; pass {attempt + 1} of {PASSES} ...")
                if code == EXIT_DONE:
                    status[step.name] = "complete"
                elif code == EXIT_STOPPED:
                    status[step.name] = "STOPPED (quota / billing / outage)"
                    stopped = True
                elif code == EXIT_PARTIAL:
                    status[step.name] = "incomplete (some queries still failing)"
                else:
                    status[step.name] = f"ERROR (exit {code}; see logs/{step.name}.log)"
                    stopped = step.llm   # a crashed LLM step would likely crash the next ones too
        except KeyboardInterrupt:
            print("\nInterrupted. Everything finished so far is saved; run the same script again to continue.")
            stopped = True

        print(f"\n{'=' * 70}\nRebuilding the report from everything saved so far ...", flush=True)
        run_step(Step("report", harness("evals/make_report.py"), llm=False))

    print(f"\n{'#' * 70}\n# STATUS\n{'#' * 70}")
    for name, st in status.items():
        print(f"  {name:28s} {st}")
    done = all(v == "complete" for v in status.values())
    if done:
        print(f"\nAll steps complete. Report: {RESULTS / 'report.md'}")
        return 0
    print(f"\nNot finished. Partial report: {RESULTS / 'report.md'}\n"
          f"Run `{Path(sys.argv[0]).name}` again (e.g. tomorrow after the daily quota resets); "
          f"it continues where it stopped.")
    return EXIT_STOPPED if stopped else EXIT_PARTIAL
